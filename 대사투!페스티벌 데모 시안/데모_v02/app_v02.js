const J=s=>String(s).normalize('NFD').replace(/[\s\u0000-/:-@[-`{-¿·…~「」“”‘’]/g,'').toLowerCase();
function lev(a,b){
  const m=a.length,n=b.length;if(!m)return n;if(!n)return m;
  let prev=Array.from({length:n+1},(_,i)=>i);
  for(let i=1;i<=m;i++){
    const cur=[i];
    for(let j=1;j<=n;j++) cur[j]=Math.min(prev[j]+1,cur[j-1]+1,prev[j-1]+(a[i-1]===b[j-1]?0:1));
    prev=cur;
  }
  return prev[n];
}
function kwScore(qj,kw){
  const kj=J(kw);if(!kj)return 0;
  if(qj.includes(kj))return 1;
  const len=kj.length, allow=len>=13?3:len>=9?2:len>=5?1:0;
  if(!allow)return 0;
  const short=len<=6; // 짧은 단어는 첫 자모가 같고 길이가 같은 경우만 오타로 인정(우천↔추천 같은 오인 방지)
  let best=0;
  for(let w=short?len:len-allow;w<=(short?len:len+allow);w++){
    for(let i=0;i+w<=qj.length;i++){
      const win=qj.slice(i,i+w);
      if(short&&win[0]!==kj[0])continue;
      const ed=lev(win,kj);
      if(ed<=allow)best=Math.max(best,1-ed/(len*1.6));
    }
  }
  return best;
}
function rankTopics(q){
  const qj=J(q);if(!qj)return [];
  return KB.map(t=>{
    let sc=0;
    for(const k of t.kw){const v=t.exact?(qj.includes(J(k))?1:0):kwScore(qj,k);if(v>0)sc+=v*(1+Math.min(J(k).length,12)/12);}
    return [t,sc>0?sc+(t.bonus||0):0];
  }).filter(x=>x[1]>0).sort((a,b)=>b[1]-a[1]);
}
function matchTopic(q){const r=rankTopics(q);return r.length&&r[0][1]>=0.7?r[0][0]:null}
function matchConcept(q){
  const qj=J(q);if(!qj)return null;
  let best=null,bs=0;
  for(const c of CONCEPTS){
    for(const k of c.kw){const v=kwScore(qj,k)*(1+Math.min(J(k).length,12)/12);if(v>bs){bs=v;best=c;}}
  }
  return bs>=0.9?best:null;
}

